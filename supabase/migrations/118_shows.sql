--    move_episode(episode, show, season, number, shift, from_show,
--    close_gap): puts a series or podcast episode at a number of a season
--    of a show (its own, or another of its kind), exactly as planMove in
--    lib/showRules.js plans it, so the page's "E7 → E3; E3–E6 become
--    E4–E7" is what gets written. A season's running order is its live and
--    in-review episodes with a number; a number more than 500 past the one
--    before it (the 1000+ numbers section 10 parks duplicates on) and the
--    ones after it are "parked" outside it (PARKED_JUMP).
--    season null = the episode's own season when it stays in its show,
--    else 1. number null = one past the highest number in the running
--    order (gaps are never filled by themselves). A free number is simply
--    taken. A number another episode holds: shift false refuses (23505);
--    shift true inserts: within the episode's own season the rows between
--    its old and new place rotate through the numbers they hold; from
--    anywhere else the holder and every row after it each take the next
--    one's number and the last takes the next free one. Every gap and
--    every other number stays where it is. close_gap: on a move out of a
--    season, the rows after it there each take the number before.
--    from_show, when given, must be the show the episode is in now (the
--    route's own show). Declined and withdrawn episodes have no place to
--    move (send it again for review first).
drop function if exists public.move_episode(text, text, integer, integer, boolean, text);
drop function if exists public.move_episode(text, text, integer, integer, boolean, text, boolean);
create function public.move_episode(
  p_id text,
  p_series_id text,
  p_season integer default null,
  p_number integer default null,
  p_shift boolean default false,
  p_from_series_id text default null,
  p_close_gap boolean default false
)
returns table (
  id text,
  series_id text,
  season integer,
  series_order integer,
  old_series_id text,
  old_season integer,
  old_series_order integer
)
language plpgsql
security definer
set search_path = ''
as $fn$
#variable_conflict use_column
declare
  c_parked_jump constant integer := 500;   -- PARKED_JUMP in lib/showRules.js
  c_max_number constant integer := 9999;   -- MAX_EPISODE_NUMBER in lib/showRules.js
  v_ep record;
  v_kind text;
  v_season integer;
  v_same boolean;
  v_regular boolean := false;
  v_cut integer;
  v_prev integer;
  v_n integer;
  v_number integer;
  v_holder text;
  v_ids text[];
  v_nums integer[];
  v_order text[];
  v_s integer;
  v_k integer;
  v_i integer;
  v_plan_ids text[] := '{}';
  v_plan_nums integer[] := '{}';
  v_old_series text[];
  v_old_seasons integer[];
  v_old_nums integer[];
begin
  if p_id is null or p_series_id is null then
    raise exception 'move_episode: name the episode and the show it goes to' using errcode = '22023';
  end if;
  if p_number is not null and (p_number < 1 or p_number > c_max_number) then
    raise exception 'move_episode: episode numbers run from 1 to %', c_max_number using errcode = '22023';
  end if;
  if p_season is not null and p_season < 1 then
    raise exception 'move_episode: seasons are numbered from 1' using errcode = '22023';
  end if;

  select e.id, e.series_id, e.season, e.series_order, e.content_type, e.status, e.withdrawn_at
    into v_ep
    from public.episodes e
   where e.id = p_id
     for update;
  if not found then
    raise exception 'move_episode: there is no episode %', p_id using errcode = '22023';
  end if;
  if p_from_series_id is not null and v_ep.series_id is distinct from p_from_series_id then
    raise exception 'move_episode: % is not in %', p_id, p_from_series_id using errcode = '22023';
  end if;
  if v_ep.content_type not in ('series', 'podcast') then
    raise exception 'move_episode: % is a % title, not a series or podcast episode', p_id, v_ep.content_type using errcode = '22023';
  end if;
  if v_ep.status = 'rejected' or v_ep.withdrawn_at is not null then
    raise exception 'move_episode: % is % and has no place to move', p_id, case when v_ep.status = 'rejected' then 'declined' else 'withdrawn' end
      using errcode = '22023';
  end if;

  select s.kind into v_kind from public.series s where s.id = p_series_id;
  if not found then
    raise exception 'move_episode: there is no show %', p_series_id using errcode = '22023';
  end if;
  if v_ep.series_id is distinct from p_series_id and v_kind <> v_ep.content_type then
    raise exception 'move_episode: % is a % episode and % is a % show', p_id, v_ep.content_type, p_series_id, v_kind
      using errcode = '22023';
  end if;

  v_season := coalesce(p_season, case when v_ep.series_id = p_series_id then v_ep.season end, 1);
  if v_season < 1 then
    raise exception 'move_episode: seasons are numbered from 1' using errcode = '22023';
  end if;
  v_same := v_ep.series_id is not distinct from p_series_id and v_ep.season is not distinct from v_season;

  -- The seasons this touches stay locked until the transaction ends.
  perform 1 from public.episodes e where e.series_id = p_series_id and e.season = v_season for update;
  if coalesce(p_close_gap, false) and not v_same and v_ep.series_id is not null then
    perform 1 from public.episodes e where e.series_id = v_ep.series_id and e.season is not distinct from v_ep.season for update;
  end if;

  -- The target season's running order, the way lib/showRules.js splits a
  -- season: with the episode in it when it is already in that order
  -- (a move inside its season), else without it.
  if v_same and v_ep.series_order is not null then
    v_prev := null;
    v_cut := null;
    for v_n in
      select distinct e.series_order
        from public.episodes e
       where e.series_id = p_series_id and e.season = v_season and e.series_order is not null
         and e.content_type in ('series', 'podcast') and e.status <> 'rejected' and e.withdrawn_at is null
       order by 1
    loop
      if v_prev is not null and v_n - v_prev > c_parked_jump then
        v_cut := v_n;
        exit;
      end if;
      v_prev := v_n;
    end loop;
    v_regular := v_cut is null or v_ep.series_order < v_cut;
  end if;
  if not v_regular then
    v_prev := null;
    v_cut := null;
    for v_n in
      select distinct e.series_order
        from public.episodes e
       where e.series_id = p_series_id and e.season = v_season and e.series_order is not null and e.id <> p_id
         and e.content_type in ('series', 'podcast') and e.status <> 'rejected' and e.withdrawn_at is null
       order by 1
    loop
      if v_prev is not null and v_n - v_prev > c_parked_jump then
        v_cut := v_n;
        exit;
      end if;
      v_prev := v_n;
    end loop;
  end if;
  select coalesce(array_agg(e.id order by e.series_order), '{}'), coalesce(array_agg(e.series_order order by e.series_order), '{}')
    into v_ids, v_nums
    from public.episodes e
   where e.series_id = p_series_id and e.season = v_season and e.series_order is not null
     and e.content_type in ('series', 'podcast') and e.status <> 'rejected' and e.withdrawn_at is null
     and (v_cut is null or e.series_order < v_cut)
     and (v_regular or e.id <> p_id);

  if p_number is null then
    select coalesce(max(x.num), 0) + 1 into v_number from unnest(v_ids, v_nums) as x(eid, num) where x.eid <> p_id;
    if v_number > c_max_number then
      raise exception 'move_episode: episode numbers run from 1 to %', c_max_number using errcode = '22023';
    end if;
  else
    v_number := p_number;
  end if;

  if v_same and v_ep.series_order is not distinct from v_number then
    return query select v_ep.id, v_ep.series_id, v_ep.season, v_ep.series_order, v_ep.series_id, v_ep.season, v_ep.series_order;
    return;
  end if;

  select e.id
    into v_holder
    from public.episodes e
   where e.series_id = p_series_id and e.season = v_season and e.series_order = v_number and e.id <> p_id
     and e.content_type in ('series', 'podcast') and e.status <> 'rejected' and e.withdrawn_at is null;

  if v_holder is null then
    v_plan_ids := array[p_id];
    v_plan_nums := array[v_number];
  elsif not coalesce(p_shift, false) then
    raise exception 'move_episode: E% of season % in % is taken by %', v_number, v_season, p_series_id, v_holder
      using errcode = '23505';
  else
    v_k := array_position(v_ids, v_holder);
    if v_k is null then
      raise exception 'move_episode: E% of season % in % sits outside the running order; give it its own number first', v_number, v_season, p_series_id
        using errcode = '22023';
    end if;
    if v_regular then
      -- Inside its season: the rows between its old and new place rotate
      -- through the numbers they hold.
      v_s := array_position(v_ids, p_id);
      v_order := array_remove(v_ids, p_id);
      v_order := v_order[1:v_k - 1] || p_id || v_order[v_k:];
      for v_i in least(v_s, v_k)..greatest(v_s, v_k) loop
        v_plan_ids := v_plan_ids || v_order[v_i];
        v_plan_nums := v_plan_nums || v_nums[v_i];
      end loop;
    else
      -- From anywhere else: it takes the holder's number, the holder and
      -- every row after it the next one's, the last the next free number.
      v_plan_ids := array[p_id];
      v_plan_nums := array[v_nums[v_k]];
      for v_i in v_k..cardinality(v_ids) loop
        v_plan_ids := v_plan_ids || v_ids[v_i];
        v_plan_nums := v_plan_nums || case when v_i < cardinality(v_ids) then v_nums[v_i + 1] else v_nums[v_i] + 1 end;
      end loop;
    end if;
  end if;

  -- Closing the gap it leaves: the season it leaves, split the same way
  -- with it still in; the rows after it each take the number before.
  if coalesce(p_close_gap, false) and not v_same and v_ep.series_id is not null and v_ep.series_order is not null then
    v_prev := null;
    v_cut := null;
    for v_n in
      select distinct e.series_order
        from public.episodes e
       where e.series_id = v_ep.series_id and e.season is not distinct from v_ep.season and e.series_order is not null
         and e.content_type in ('series', 'podcast') and e.status <> 'rejected' and e.withdrawn_at is null
       order by 1
    loop
      if v_prev is not null and v_n - v_prev > c_parked_jump then
        v_cut := v_n;
        exit;
      end if;
      v_prev := v_n;
    end loop;
    if v_cut is null or v_ep.series_order < v_cut then
      select coalesce(array_agg(e.id order by e.series_order), '{}'), coalesce(array_agg(e.series_order order by e.series_order), '{}')
        into v_ids, v_nums
        from public.episodes e
       where e.series_id = v_ep.series_id and e.season is not distinct from v_ep.season and e.series_order is not null
         and e.content_type in ('series', 'podcast') and e.status <> 'rejected' and e.withdrawn_at is null
         and (v_cut is null or e.series_order < v_cut);
      v_s := array_position(v_ids, p_id);
      for v_i in (v_s + 1)..cardinality(v_ids) loop
        v_plan_ids := v_plan_ids || v_ids[v_i];
        v_plan_nums := v_plan_nums || v_nums[v_i - 1];
      end loop;
    end if;
  end if;

  -- Where every row in the plan is now, for the answer.
  select array_agg(e.series_id order by r.ord), array_agg(e.season order by r.ord), array_agg(e.series_order order by r.ord)
    into v_old_series, v_old_seasons, v_old_nums
    from unnest(v_plan_ids) with ordinality as r(eid, ord)
    join public.episodes e on e.id = r.eid;

  -- Out of the way: the episode out of every number, every other row in
  -- the plan below the lowest number of its own season.
  update public.episodes e set series_order = null where e.id = p_id;
  update public.episodes e
     set series_order = (
           select least(coalesce(min(x.series_order), 0), 0)
             from public.episodes x
            where x.series_id = e.series_id and x.season is not distinct from e.season
         ) - r.ord::integer
    from unnest(v_plan_ids) with ordinality as r(eid, ord)
   where e.id = r.eid and e.id <> p_id;

  -- Into place.
  update public.episodes e
     set series_id = case when e.id = p_id then p_series_id else e.series_id end,
         season = case when e.id = p_id then v_season else e.season end,
         series_order = r.num
    from unnest(v_plan_ids, v_plan_nums) as r(eid, num)
   where e.id = r.eid;

  return query
    select e.id, e.series_id, e.season, e.series_order, r.os, r.oseason, r.onum
      from unnest(v_plan_ids, v_old_series, v_old_seasons, v_old_nums) with ordinality as r(eid, os, oseason, onum, ord)
      join public.episodes e on e.id = r.eid
     order by (e.id <> p_id), r.ord;
end;
