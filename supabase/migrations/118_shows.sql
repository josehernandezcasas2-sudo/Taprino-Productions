-- 14. Renumbering in one go. Both functions check that every episode they
--    are given is where the caller says it is, move the rows they change
--    out of the way first (to negative numbers under their season's
--    lowest; the episode move_episode moves to no number at all), then to
--    their final numbers, all in one transaction, so the unique index
--    never sees two on one number. They
--    answer every row they placed: id, series_id, season, series_order
--    (now) and old_series_id, old_season, old_series_order (before), so
--    the page can say exactly what changed. Errors: SQLSTATE 22023 for a
--    request that doesn't fit (an episode not in that show or season,
--    listed twice, a number outside 1-9999, a show of another kind), 23505
--    for a number another episode holds (PostgREST answers 400 and 409).
--    The page plans every move with lib/showRules.js (planMove, whose
--    same-season plans arrive here as reorder_show_season's ids and
--    numbers); scripts/check-migration-118.mjs runs both on the same rows.
--
--    reorder_show_season(show, season, ids, numbers): gives ids[i] the
--    number numbers[i] (or i, when numbers is null). Every id must be an
--    episode of that show and season (a null season means "no season").
--    A number may not be one held by an episode of the season that isn't
--    in the list.
drop function if exists public.reorder_show_season(text, integer, text[], integer[]);
create function public.reorder_show_season(
  p_series_id text,
  p_season integer,
  p_ids text[],
  p_numbers integer[] default null
)
returns table (
  id text,
  series_id text,
  season integer,
  series_order integer,
  old_series_id text,
  old_season integer,
  old_series_order integer
)
language plpgsql
security definer
set search_path = ''
as $fn$
#variable_conflict use_column
declare
  v_n integer := coalesce(cardinality(p_ids), 0);
  v_bad text;
  v_floor integer;
  v_old integer[];
begin
  if p_series_id is null or v_n = 0 then
    raise exception 'reorder_show_season: name a show and at least one episode' using errcode = '22023';
  end if;
  if array_position(p_ids, null) is not null
     or (select count(distinct x.eid) from unnest(p_ids) as x(eid)) <> v_n then
    raise exception 'reorder_show_season: an episode is missing or listed twice' using errcode = '22023';
  end if;
  if p_numbers is not null then
    if coalesce(cardinality(p_numbers), 0) <> v_n then
      raise exception 'reorder_show_season: % episodes but % numbers', v_n, coalesce(cardinality(p_numbers), 0) using errcode = '22023';
    end if;
    if exists (select 1 from unnest(p_numbers) as x(num) where x.num is null or x.num < 1 or x.num > 9999) then
      raise exception 'reorder_show_season: episode numbers run from 1 to 9999' using errcode = '22023';
    end if;
    if (select count(distinct x.num) from unnest(p_numbers) as x(num)) <> v_n then
      raise exception 'reorder_show_season: two episodes were given the same number' using errcode = '22023';
    end if;
  end if;

  -- The season's rows stay locked until the transaction ends, so two
  -- renumberings of one season can't interleave.
  perform 1
     from public.episodes e
    where e.series_id = p_series_id
      and e.season is not distinct from p_season
      for update;

  select string_agg(x.eid, ', ' order by x.ord)
    into v_bad
    from unnest(p_ids) with ordinality as x(eid, ord)
   where not exists (
     select 1
       from public.episodes e
      where e.id = x.eid
        and e.series_id = p_series_id
        and e.season is not distinct from p_season
   );
  if v_bad is not null then
    raise exception 'reorder_show_season: not in % season %: %', p_series_id, coalesce(p_season::text, 'none'), v_bad
      using errcode = '22023';
  end if;

  select string_agg(format('E%s (held by %s)', t.num, o.id), ', ' order by t.num)
    into v_bad
    from (
      select x.eid,
             case when p_numbers is null then x.ord::integer else p_numbers[x.ord::integer] end as num
        from unnest(p_ids) with ordinality as x(eid, ord)
    ) t
    join public.episodes m on m.id = t.eid
    join public.episodes o
      on o.series_id = p_series_id
     and o.season is not distinct from p_season
     and o.series_order = t.num
     and not (o.id = any (p_ids))
   where m.content_type in ('series', 'podcast') and m.status <> 'rejected' and m.withdrawn_at is null
     and o.content_type in ('series', 'podcast') and o.status <> 'rejected' and o.withdrawn_at is null;
  if v_bad is not null then
    raise exception 'reorder_show_season: taken in % season %: %', p_series_id, coalesce(p_season::text, 'none'), v_bad
      using errcode = '23505';
  end if;

  select array_agg(e.series_order order by x.ord)
    into v_old
    from unnest(p_ids) with ordinality as x(eid, ord)
    join public.episodes e on e.id = x.eid;

  -- Out of the way: below the lowest number in the season, so these can
  -- land on nothing.
  select least(coalesce(min(e.series_order), 0), 0)
    into v_floor
    from public.episodes e
   where e.series_id = p_series_id
     and e.season is not distinct from p_season;
  update public.episodes e
     set series_order = (v_floor - x.ord)::integer
    from unnest(p_ids) with ordinality as x(eid, ord)
   where e.id = x.eid;

  -- Into place.
  update public.episodes e
     set series_order = case when p_numbers is null then x.ord::integer else p_numbers[x.ord::integer] end
    from unnest(p_ids) with ordinality as x(eid, ord)
   where e.id = x.eid;

  return query
    select e.id, e.series_id, e.season, e.series_order, e.series_id, e.season, x.old_num
      from unnest(p_ids, v_old) with ordinality as x(eid, old_num, ord)
      join public.episodes e on e.id = x.eid
     order by x.ord;
end;
$fn$;

