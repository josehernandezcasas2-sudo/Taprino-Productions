-- 118: Shows (the series revamp, slice 1; 2026-11-02). The data side of the
-- show page in mockups/series-revamp-spec.md: what a show knows about
-- itself, honest episode numbers, who a title pays (Jose's decisions 19-21)
-- and decision 2's "Make it public". Nothing a viewer or a creator sees
-- changes until the code that reads these columns ships, and that code
-- reads a missing column as absent until this has run.
--
-- In order, the numbered sections below:
--   1  series.status: a null becomes 'approved' (how the site already
--      treated it); the check that a show is pending, approved or rejected
--      is added unless a show has another value (listed, nothing refused).
--   2  series.creator_id: an unowned show gets an owner only when every
--      episode in it was uploaded by one account; the rest are listed.
--   3  series.kind (series | podcast | vertical), from the episodes' types.
--   4  series.defaults: what each new episode starts from, taken once from
--      what most of the show's episodes have, the newest breaking a tie.
--   5  series: season labels, the take-down note, the Clerk ids of who
--      submitted and reviewed it, who it pays, its credits.
--   6  series.public_at and decision 2: an approved show with an approved
--      episode stays public, since its first release; an approved show
--      without one becomes private (pending); a pending show with an
--      approved episode is listed as ready to go public. Nothing anyone
--      can watch appears or disappears.
--   7  episodes: its own page, its notes, a staged replacement video, who
--      it pays, its credits, the "captions may be out of sync" flag.
--   8  a show episode with no season is in season 1.
--   9  an episode numbered 0 or below loses the number.
--  10  two episodes on one number in a season: the first keeps it (a live
--      one before one in review, then the older), each other one moves
--      past the season's highest number + 1000.
--  11  if two still share a number, stop before the index.
--  12  the unique index: one episode per number per season of a show.
--  13  extras: the index on their parent covers any title with a parent.
--  14  reorder_show_season and move_episode: renumbering in one go.
--  15  payee_invites and title_payees (who a title pays, from when).
--  16  series_drop_runs (where the saver-notice cron got to).
--  17  row level security on every table this touches, the API reload.
--
-- Every row it changes is named in a notice and in the table the SQL
-- Editor shows at the end ("What 118 changed"). The SQL Editor runs the
-- file as one transaction: if anything stops it, nothing is kept.
--
-- Safe to run again. Two steps run only the first time, keyed on the
-- column they create: section 4's defaults and section 6's moves (private,
-- ready to go public). Everything else only fills what is still empty or
-- fixes what is still wrong, so a second run changes nothing the first one
-- did (it lists the shows still without an owner again).


-- 0. A notebook for this run: every change is raised as a notice and kept
--    here, and the last statement shows the lot. Temporary: gone with the
--    session.
create temp table if not exists m118_report (
  n integer generated by default as identity,
  topic text not null,
  line text not null
);
truncate pg_temp.m118_report restart identity;

create or replace function pg_temp.m118_note(p_topic text, p_line text)
returns void
language plpgsql
as $note$
begin
  insert into pg_temp.m118_report (topic, line) values (p_topic, p_line);
  raise notice '118 %: %', p_topic, p_line;
end;
$note$;

create or replace function pg_temp.m118_has_column(p_table text, p_column text)
returns boolean
language sql
stable
as $has$
  select exists (
    select 1
      from pg_attribute
     where attrelid = to_regclass('public.' || p_table)
       and attname = p_column
       and attnum > 0
       and not attisdropped
  );
$has$;


-- 1. A show's status. 053 added the column as not null default
--    'approved', and the code still reads a null as approved (rows from
--    before 053). Make that true in the data, keep the column not null,
--    and add the check, unless a show carries a value the code doesn't
--    know: then it is listed for Jose instead of refusing the run.
do $$
declare
  r record;
begin
  for r in select s.id, s.name from public.series s where s.status is null order by s.id loop
    update public.series set status = 'approved' where id = r.id;
    perform pg_temp.m118_note('status', format('%s (%s) had no status; it is approved now, which is how the site already treated it.', r.name, r.id));
  end loop;
end $$;

alter table public.series alter column status set not null;

do $$
begin
  if not exists (
    select 1
      from pg_attrdef d
      join pg_attribute a on a.attrelid = d.adrelid and a.attnum = d.adnum
     where d.adrelid = 'public.series'::regclass and a.attname = 'status'
  ) then
    alter table public.series alter column status set default 'approved';
  end if;
end $$;

do $$
declare
  v_odd text;
begin
  if exists (select 1 from pg_constraint where conrelid = 'public.series'::regclass and conname = 'series_status_check') then
    return;
  end if;
  select string_agg(format('%s (%s)', s.id, s.status), ', ' order by s.id)
    into v_odd
    from public.series s
   where s.status not in ('pending', 'approved', 'rejected');
  if v_odd is null then
    alter table public.series add constraint series_status_check check (status in ('pending', 'approved', 'rejected'));
  else
    perform pg_temp.m118_note('check', format('The status check was not added: %s. A show is pending, approved or rejected; set these by hand and run 118 again.', v_odd));
  end if;
end $$;


-- 2. A show's owner. creator_id came with 038; older shows were "owned"
--    by whoever had an episode in them. Fill it only where that is
--    unambiguous: every episode filed under the show was uploaded by the
--    same account (a Clerk id). Every show still without an owner is
--    listed, so an admin can set it on /admin/ownership.
do $$
declare
  r record;
begin
  for r in
    select s.id, s.name, u.uploader
      from public.series s
      join (
        select e.series_id, min(e.submitted_by) as uploader
          from public.episodes e
         where e.series_id is not null
         group by e.series_id
        having count(distinct e.submitted_by) = 1
           and bool_and(e.submitted_by is not null)
           and min(e.submitted_by) like 'user\_%'
      ) u on u.series_id = s.id
     where s.creator_id is null
     order by s.id
  loop
    update public.series set creator_id = r.uploader where id = r.id and creator_id is null;
    perform pg_temp.m118_note('owner', format('%s (%s) belongs to %s now: they uploaded every episode in it.', r.name, r.id, r.uploader));
  end loop;

  for r in
    select s.id, s.name,
           count(e.id) as episodes,
           count(distinct e.submitted_by) as uploaders,
           bool_or(e.id is not null and e.submitted_by is null) as some_unknown,
           string_agg(distinct e.submitted_by, ', ') as who
      from public.series s
      left join public.episodes e on e.series_id = s.id
     where s.creator_id is null
     group by s.id, s.name
     order by s.id
  loop
    perform pg_temp.m118_note('unowned', format('%s (%s) has no owner: %s. Set one on /admin/ownership.', r.name, r.id,
      case
        when r.episodes = 0 then 'it has no episodes'
        when r.uploaders > 1 then format('its %s episodes come from %s accounts (%s)', r.episodes, r.uploaders, r.who)
        when r.some_unknown then 'some of its episodes have no uploader'
        else format('its uploader (%s) is not an account id', r.who)
      end));
  end loop;
end $$;


-- 3. What kind of show it is: decides the words (show / episode, "Hosted
--    by"), which episodes it takes and which public page it has. A show
--    whose episodes are podcasts (and none a series episode) is a podcast;
--    one whose episodes are all vertical is a vertical (Snippet) series,
--    left as it is; everything else, empty shows included, is a series.
--    Each run only moves a show still at the default 'series' to what its
--    episodes say, so nothing set on purpose is undone.
do $$
begin
  if not pg_temp.m118_has_column('series', 'kind') then
    alter table public.series add column kind text not null default 'series';
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.series'::regclass and conname = 'series_kind_check') then
    alter table public.series add constraint series_kind_check check (kind in ('series', 'podcast', 'vertical'));
  end if;
end $$;

do $$
declare
  r record;
begin
  for r in
    select s.id, s.name, k.kind
      from public.series s
      join (
        select e.series_id,
               case
                 when bool_or(e.content_type = 'podcast') and not bool_or(e.content_type = 'series') then 'podcast'
                 when bool_and(e.content_type = 'vertical') then 'vertical'
                 else 'series'
               end as kind
          from public.episodes e
         where e.series_id is not null
           and e.content_type <> 'bonus'
         group by e.series_id
      ) k on k.series_id = s.id
     where s.kind = 'series'
       and k.kind <> 'series'
     order by s.id
  loop
    update public.series set kind = r.kind where id = r.id;
    perform pg_temp.m118_note('kind', format('%s (%s) is a %s show.', r.name, r.id, r.kind));
  end loop;
end $$;


-- 4. A show's defaults: { tier, rating, mainGenre, genre, artist,
--    adsEnabled }, copied onto each episode added from now on (never read
--    in place of an episode's own rating or tier). For a show that already
--    has episodes, each value is the one most of them have (an episode
--    without one doesn't vote; a declined episode only when the show has
--    nothing else), the newest episode breaking a tie, so a show with a
--    free first episode and the rest Tapa + defaults to Tapa +. Done once,
--    when the column is made: a show's defaults are its owner's after that.
do $$
declare
  v_count integer;
begin
  if pg_temp.m118_has_column('series', 'defaults') then
    return;
  end if;
  alter table public.series add column defaults jsonb not null default '{}'::jsonb;
  alter table public.series add constraint series_defaults_object check (jsonb_typeof(defaults) = 'object');

  with eps as (
    select e.series_id, e.id, e.status, e.created_at, e.season, e.series_order,
           e.tier, e.rating, e.main_genre, e.genre, e.artist, e.ads_enabled,
           bool_or(e.status <> 'rejected') over (partition by e.series_id) as has_open
      from public.episodes e
     where e.series_id is not null
       and e.content_type <> 'bonus'
  ), pool as (
    select * from eps where status <> 'rejected' or not has_open
  ), votes as (
    select series_id, 'tier' as k, to_jsonb(tier) as val, created_at, season, series_order, id from pool where tier is not null
    union all
    select series_id, 'rating', to_jsonb(btrim(rating)), created_at, season, series_order, id from pool where nullif(btrim(rating), '') is not null
    union all
    select series_id, 'mainGenre', to_jsonb(btrim(main_genre)), created_at, season, series_order, id from pool where nullif(btrim(main_genre), '') is not null
    union all
    select series_id, 'genre', to_jsonb(btrim(genre)), created_at, season, series_order, id from pool where nullif(btrim(genre), '') is not null
    union all
    select series_id, 'artist', to_jsonb(btrim(artist)), created_at, season, series_order, id from pool where nullif(btrim(artist), '') is not null
    union all
    select series_id, 'adsEnabled', to_jsonb(ads_enabled), created_at, season, series_order, id from pool where ads_enabled is not null
  ), ranked as (
    select v.series_id, v.k, v.val,
           row_number() over (
             partition by v.series_id, v.k
             order by v.created_at desc, v.season desc nulls last, v.series_order desc nulls last, v.id desc
           ) as recency
      from votes v
  ), tallied as (
    select series_id, k, val, count(*) as n, min(recency) as newest
      from ranked
     group by series_id, k, val
  ), picked as (
    select distinct on (series_id, k) series_id, k, val
      from tallied
     order by series_id, k, n desc, newest
  )
  update public.series s
     set defaults = d.obj
    from (select series_id, jsonb_object_agg(k, val) as obj from picked group by series_id) d
   where s.id = d.series_id;
  get diagnostics v_count = row_count;
  if v_count > 0 then
    perform pg_temp.m118_note('defaults', format('%s %s took their defaults for new episodes (Who can watch, rating, genres, Made by, ads) from what most of their episodes have.', v_count, case when v_count = 1 then 'show' else 'shows' end));
  end if;
end $$;


