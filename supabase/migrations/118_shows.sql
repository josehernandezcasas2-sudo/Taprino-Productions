-- 6. When a show went public (decision 2: once an episode is approved, its
--    owner or a full admin presses Make it public; later episodes go live
--    as they are approved). On the day this runs:
--    - an approved show with an approved episode (or an approved extra
--      filed under the show) stays public, public_at = its first release;
--    - an approved show with none becomes private (pending) and is listed:
--      there is nothing in it anyone could watch;
--    - a pending show with an approved episode stays private and is listed
--      as ready to go public.
--    "Approved" counts an approved episode even when it is withdrawn, held
--    or waiting on removal, so a buyer never loses a title over this.
--    Only the first run moves shows; a later run only fills public_at for
--    an approved show that has an approved episode and no public_at.
do $$
declare
  v_first boolean := not pg_temp.m118_has_column('series', 'public_at');
  v_count integer;
  r record;
begin
  if v_first then
    alter table public.series add column public_at timestamptz;
  end if;

  update public.series s
     set public_at = least(x.first_release, now())
    from (
      select a.series_id, min(a.released) as first_release
        from (
          select e.series_id, coalesce(e.released_at, e.available_from, e.reviewed_at, e.created_at) as released
            from public.episodes e
           where e.status = 'approved'
             and e.series_id is not null
          union all
          select e.bonus_parent_id, coalesce(e.released_at, e.available_from, e.reviewed_at, e.created_at)
            from public.episodes e
           where e.status = 'approved'
             and e.content_type = 'bonus'
             and e.bonus_parent_type = 'series'
             and e.bonus_parent_id is not null
        ) a
       group by a.series_id
    ) x
   where s.id = x.series_id
     and s.status = 'approved'
     and s.public_at is null;
  get diagnostics v_count = row_count;
  if v_count > 0 then
    perform pg_temp.m118_note('public', format('%s approved %s with an approved episode %s public; public_at is the first episode''s release.', v_count, case when v_count = 1 then 'show' else 'shows' end, case when v_count = 1 then 'stays' else 'stay' end));
  end if;

  if not v_first then
    return;
  end if;

  for r in
    select s.id, s.name
      from public.series s
     where s.status = 'approved'
       and s.public_at is null
     order by s.id
  loop
    update public.series set status = 'pending' where id = r.id;
    perform pg_temp.m118_note('private', format('%s (%s) had no approved episode, so it is private now (pending): its owner makes it public once one is approved.', r.name, r.id));
  end loop;

  for r in
    select s.id, s.name, count(e.id) as approved
      from public.series s
      join public.episodes e on e.series_id = s.id and e.status = 'approved'
     where s.status = 'pending'
     group by s.id, s.name
     order by s.id
  loop
    perform pg_temp.m118_note('ready', format('Ready to go public: %s (%s) has %s approved episode%s and waits for its owner (or a full admin) to make it public.', r.name, r.id, r.approved, case when r.approved = 1 then '' else 's' end));
  end loop;
end $$;


