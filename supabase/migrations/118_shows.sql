-- 8. A series or podcast episode with no season is in season 1 (the new
--    sorter reads a missing season as 1; one old sort put it first).
do $$
declare
  v_count integer;
begin
  update public.episodes
     set season = 1
   where series_id is not null
     and season is null
     and content_type in ('series', 'podcast');
  get diagnostics v_count = row_count;
  if v_count > 0 then
    perform pg_temp.m118_note('season', format('%s show %s had no season; %s in season 1 now.', v_count, case when v_count = 1 then 'episode' else 'episodes' end, case when v_count = 1 then 'it is' else 'they are' end));
  end if;
end $$;


-- 9. Episode numbers start at 1. A series or podcast episode numbered 0 or
--    below loses its number (its owner gives it one on the show page),
--    each one listed.
do $$
declare
  r record;
begin
  for r in
    select e.id, e.title, e.series_id, e.season, e.series_order, coalesce(s.name, e.series_id) as show
      from public.episodes e
      left join public.series s on s.id = e.series_id
     where e.series_id is not null
       and e.series_order <= 0
       and e.content_type in ('series', 'podcast')
     order by e.series_id, e.season, e.series_order, e.id
  loop
    update public.episodes set series_order = null where id = r.id;
    perform pg_temp.m118_note('unnumbered', format('%s (%s) season %s: "%s" (%s) was numbered E%s; it has no number now, for its owner to give it one.',
      r.show, r.series_id, coalesce(r.season::text, '?'), r.title, r.id, r.series_order));
  end loop;
end $$;


-- 10. Two episodes on one number in the same season of a show. The first
--    keeps the number: a live (approved) episode before one in review,
--    then the older. Each other one moves to the season's highest number
--    + 1000 + its place in line, past every number in that season, so no
--    move can land on another; the show page then shows the gap and the
--    owner puts it where it belongs. Declined and withdrawn episodes hold
--    no number (the index below skips them), so they are never moved.
do $$
declare
  r record;
begin
  for r in
    with scope as (
      select e.id, e.title, e.series_id, e.season, e.series_order, e.status, e.created_at
        from public.episodes e
       where e.series_id is not null
         and e.season is not null
         and e.series_order is not null
         and e.content_type in ('series', 'podcast')
         and e.status <> 'rejected'
         and e.withdrawn_at is null
    ), ranked as (
      select sc.*,
             row_number() over (
               partition by sc.series_id, sc.season, sc.series_order
               order by (sc.status = 'approved') desc, sc.created_at, sc.id
             ) as rn
        from scope sc
    ), tops as (
      select e.series_id, e.season, max(e.series_order) as top
        from public.episodes e
       where e.series_id is not null
         and e.season is not null
         and e.series_order is not null
       group by e.series_id, e.season
    ), moves as (
      select rk.id, rk.title, rk.series_id, rk.season, rk.series_order,
             t.top + 1000 + row_number() over (
               partition by rk.series_id, rk.season
               order by rk.series_order, rk.created_at, rk.id
             ) as new_order
        from ranked rk
        join tops t on t.series_id = rk.series_id and t.season = rk.season
       where rk.rn > 1
    )
    select m.id, m.title, m.series_id, m.season, m.series_order, m.new_order::integer as new_order,
           coalesce(s.name, m.series_id) as show,
           k.id as kept_id, k.title as kept_title
      from moves m
      join ranked k on k.series_id = m.series_id and k.season = m.season and k.series_order = m.series_order and k.rn = 1
      left join public.series s on s.id = m.series_id
     order by m.series_id, m.season, m.new_order
  loop
    update public.episodes set series_order = r.new_order where id = r.id;
    perform pg_temp.m118_note('renumbered', format('%s (%s) season %s: "%s" (%s) moved from E%s to E%s; E%s stays with "%s" (%s).',
      r.show, r.series_id, r.season, r.title, r.id, r.series_order, r.new_order, r.series_order, r.kept_title, r.kept_id));
  end loop;
end $$;


-- 11. Nothing may still share a number. If anything does, stop here with
--    the list: the SQL Editor runs this file as one transaction, so
--    nothing above is kept, and the index is never half made.
do $$
declare
  v_dups text;
begin
  select string_agg(format('%s season %s E%s: %s', d.series_id, d.season, d.series_order, d.ids), '; ' order by d.series_id, d.season, d.series_order)
    into v_dups
    from (
      select e.series_id, e.season, e.series_order, string_agg(e.id, ', ' order by e.id) as ids
        from public.episodes e
       where e.series_id is not null
         and e.season is not null
         and e.series_order is not null
         and e.content_type in ('series', 'podcast')
         and e.status <> 'rejected'
         and e.withdrawn_at is null
       group by e.series_id, e.season, e.series_order
      having count(*) > 1
    ) d;
  if v_dups is not null then
    raise exception 'Migration 118 stopped before the unique index: these episodes still share a number: %', v_dups
      using hint = 'The SQL Editor runs this file as one transaction, so nothing from this run was kept. Renumber these episodes and run 118 again.';
  end if;
end $$;


-- 12. One episode per number per season of a show, at last enforced by the
--    database. Declined (rejected) and withdrawn episodes don't hold a
--    number; one waiting on removal does (a denied removal restores it).
--    Extras and vertical clips have no place in this order.
create unique index if not exists episodes_show_position_uq
  on public.episodes (series_id, season, series_order)
  where series_id is not null
    and season is not null
    and series_order is not null
    and content_type in ('series', 'podcast')
    and status <> 'rejected'
    and withdrawn_at is null;


-- 13. Extras. 024 indexed (bonus_parent_type, bonus_parent_id) for
--    content_type 'bonus' only; the show page looks extras up by their
--    parent alone (an extra anchored to a show or to one episode), so the
--    same index now covers any row that has a parent.
do $$
begin
  if exists (
    select 1
      from pg_indexes
     where schemaname = 'public'
       and indexname = 'episodes_bonus_parent_idx'
       and indexdef not ilike '%bonus_parent_id IS NOT NULL%'
  ) then
    drop index public.episodes_bonus_parent_idx;
  end if;
