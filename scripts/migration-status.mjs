// Which numbered migrations are really in a database? Writes
// supabase/check_migrations.sql: one read-only query to paste into the
// Supabase SQL Editor, which answers with every migration whose objects
// are missing (NOT RUN / PARTLY RUN and what is missing), or one line
// saying everything is in.
//
// Why: 117 failed on 2026-11-03 with "relation ad_impression_days does
// not exist" although 103 was noted as run on 2026-10-25, so "Jose ran
// it" is not proof. The checks are not hand-written: PGlite (a real
// Postgres) builds the database from schema.sql and runs the migrations in
// order, taking a snapshot of the catalogue after each one (tables and
// views, columns, column types, functions by signature, indexes,
// triggers, constraints, row level security). What a migration adds is
// the difference; an object still there at the end belongs to the last
// migration that added it, and up to three per migration (tables and
// functions first) become its checks. Then the query is proved on three
// databases: the whole chain (everything in), the chain to 102 (103 on
// reported NOT RUN, nothing before it), and the whole chain with one
// table dropped (that migration PARTLY RUN).
//
// Needs PGlite (see scripts/pg-chain.mjs). Run after every new migration:
//   node scripts/migration-status.mjs
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { buildDb, migrationFiles, runMigration, SUPABASE_DIR } from './pg-chain.mjs';

const PER_MIGRATION = 3;
const OUT = path.join(SUPABASE_DIR, 'check_migrations.sql');

const SNAPSHOT = `
select 't' as k, c.relname as x from pg_class c join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'public' and c.relkind in ('r', 'v', 'm', 'p')
union all
select 'c', table_name || '.' || column_name from information_schema.columns where table_schema = 'public'
union all
select 'y', table_name || '.' || column_name || ':' || data_type from information_schema.columns where table_schema = 'public'
union all
select 'f', p.oid::regprocedure::text from pg_proc p join pg_namespace n on n.oid = p.pronamespace
 where n.nspname = 'public'
union all
select 'i', c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'public' and c.relkind = 'i'
union all
select 'g', c.relname || '.' || t.tgname from pg_trigger t join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and not t.tgisinternal
union all
select 'k', k.conname from pg_constraint k join pg_namespace n on n.oid = k.connamespace where n.nspname = 'public'
union all
select 'r', c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'public' and c.relkind = 'r' and c.relrowsecurity`;

const keyOf = (o) => `${o.k}:${o.x}`;
async function snapshot(db) {
  const { rows } = await db.query(SNAPSHOT);
  return new Set(rows.map(keyOf));
}

// Tables first: one missing table says "not run" more plainly than a column.
const PRIORITY = { t: 0, f: 1, c: 2, y: 3, g: 4, k: 5, i: 6, r: 7 };
const LABEL = { t: 'table', f: 'function', c: 'column', y: 'column type', g: 'trigger', k: 'constraint', i: 'index', r: 'row level security on' };

// The table an object hangs on, where the key says it.
const tableOf = (o) => (o.k === 't' || o.k === 'r' ? o.x : /^[cyg]$/.test(o.k) ? o.x.split('.')[0] : o.x);

function pickChecks(objects) {
  const sorted = [...objects].sort((a, b) => PRIORITY[a.k] - PRIORITY[b.k] || a.x.localeCompare(b.x));
  const picked = [];
  const tables = new Set();
  // Spread over as many tables as the migration touched, so a migration
  // that only partly ran still shows as partly; then whatever is left.
  for (const o of sorted) {
    if (picked.length < PER_MIGRATION && !tables.has(tableOf(o))) { picked.push(o); tables.add(tableOf(o)); }
  }
  for (const o of sorted) if (picked.length < PER_MIGRATION && !picked.includes(o)) picked.push(o);
  return picked;
}

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

function buildQuery(checks, last) {
  const values = checks.map((c) => `  (${c.m}, ${lit(c.k)}, ${lit(c.x)})`).join(',\n');
  return `-- Which migrations are in this database? Read-only: it changes nothing.
-- Paste all of it into the Supabase SQL Editor and press Run. The answer is
-- one row per migration that is missing (NOT RUN, or PARTLY RUN with what
-- is missing); run those migrations in order, then run this again. A
-- single row "every migration through ${last} is in" means nothing is missing.
-- Generated by scripts/migration-status.mjs from schema.sql and migrations
-- 002–${last} (up to ${PER_MIGRATION} objects each); regenerate after a new migration.
with want(m, k, x) as (values
${values}
), got as (
  select m, k, x, case k
    when 't' then to_regclass('public.' || quote_ident(x)) is not null
    when 'i' then to_regclass('public.' || quote_ident(x)) is not null
    when 'c' then exists (select 1 from information_schema.columns c
                   where c.table_schema = 'public' and c.table_name = split_part(x, '.', 1)
                     and c.column_name = split_part(x, '.', 2))
    when 'y' then exists (select 1 from information_schema.columns c
                   where c.table_schema = 'public' and c.table_name = split_part(x, '.', 1)
                     and c.column_name = split_part(split_part(x, '.', 2), ':', 1)
                     and c.data_type = split_part(x, ':', 2))
    when 'f' then to_regprocedure('public.' || x) is not null
    when 'g' then exists (select 1 from pg_trigger t join pg_class c on c.oid = t.tgrelid
                   join pg_namespace n on n.oid = c.relnamespace
                   where n.nspname = 'public' and c.relname = split_part(x, '.', 1)
                     and t.tgname = split_part(x, '.', 2))
    when 'k' then exists (select 1 from pg_constraint k join pg_namespace n on n.oid = k.connamespace
                   where n.nspname = 'public' and k.conname = x)
    when 'r' then exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
                   where n.nspname = 'public' and c.relname = x and c.relrowsecurity)
  end as ok
  from want
), per as (
  select m, bool_and(ok) as all_in, bool_or(ok) as some_in,
         string_agg(case when not ok then case k
           when 't' then 'table ' when 'f' then 'function ' when 'c' then 'column '
           when 'y' then 'column type ' when 'g' then 'trigger ' when 'k' then 'constraint '
           when 'i' then 'index ' when 'r' then 'row level security on ' end || x end, ', ') as missing
    from got group by m
)
-- Migration 112's rule: once it is in, every table has row level security.
-- A table made later by a migration run out of order can miss it.
, open_tables as (
  select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity
     and exists (select 1 from per where m = 112 and all_in)
)
select migration, state, missing from (
  select m as ord, lpad(m::text, 3, '0') as migration,
         case when some_in then 'PARTLY RUN' else 'NOT RUN' end as state, missing
    from per where not all_in
  union all
  select 99999, 'rls', 'ROW LEVEL SECURITY OFF (run what is in the next column)',
         string_agg(format('alter table %I enable row level security;', relname), ' ' order by relname)
    from open_tables having count(*) > 0
  union all
  select 100000, 'all',
         case when exists (select 1 from per where not all_in) or exists (select 1 from open_tables)
              then 'fix the rows above (migrations oldest first), then run this again'
              else 'every migration through ${last} is in' end, null
) answer order by ord;
`;
}

// --- 1. what each migration adds ---------------------------------------------
const files = migrationFiles().filter((f) => Number(f.slice(0, 3)) >= 2);
const last = Number(files[files.length - 1].slice(0, 3));
const db = await buildDb(1);
let before = await snapshot(db);
const owner = new Map(); // object key -> { m, k, x }
for (const f of files) {
  const m = Number(f.slice(0, 3));
  await runMigration(db, m);
  const after = await snapshot(db);
  const addedCols = new Set();
  for (const key of after) if (!before.has(key) && key.startsWith('c:')) addedCols.add(key.slice(2));
  for (const key of after) {
    if (before.has(key)) continue;
    const k = key[0];
    const x = key.slice(2);
    // A new column's type is not news; a changed type on an old column is.
    if (k === 'y' && addedCols.has(x.slice(0, x.lastIndexOf(':')))) continue;
    owner.set(key, { m, k, x });
  }
  before = after;
}
for (const key of [...owner.keys()]) if (!before.has(key)) owner.delete(key);

const byMigration = new Map();
for (const o of owner.values()) {
  if (!byMigration.has(o.m)) byMigration.set(o.m, []);
  byMigration.get(o.m).push(o);
}
const checks = [];
const unchecked = [];
for (const f of files) {
  const m = Number(f.slice(0, 3));
  const objs = byMigration.get(m) || [];
  if (!objs.length) { unchecked.push(f); continue; }
  for (const o of pickChecks(objs)) checks.push(o);
}

const QUERY = buildQuery(checks, last);
fs.writeFileSync(OUT, QUERY);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${checks.length} checks for ${files.length - unchecked.length} migrations`);
if (unchecked.length) console.log(`nothing of their own left to check (data, grants, changed rules): ${unchecked.join(', ')}`);

// --- 2. proof ------------------------------------------------------------------
const answer = async (d) => (await d.query(QUERY)).rows;
const checked = [...new Set(checks.map((c) => c.m))];

const full = await answer(db);
assert.deepEqual(full, [{ migration: 'all', state: `every migration through ${last} is in`, missing: null }], 'the whole chain: everything is in');
console.log(`ok  the whole chain answers "every migration through ${last} is in"`);

const at102 = await buildDb(102);
const rows102 = await answer(at102);
const notRun = rows102.filter((r) => r.migration !== 'all');
assert.deepEqual(notRun.map((r) => Number(r.migration)), checked.filter((m) => m > 102), 'the chain to 102: exactly the checked migrations after 102');
assert.ok(notRun.every((r) => r.state === 'NOT RUN'), 'the chain to 102: each one NOT RUN');
assert.match(rows102[rows102.length - 1].state, /fix the rows above/);
assert.match(notRun.find((r) => r.migration === '103').missing, /table ad_impression_days/);
console.log(`ok  the chain to 102 answers NOT RUN for ${notRun.map((r) => r.migration).join(', ')}`);

await db.exec('alter table purchases disable row level security;');
const open = (await answer(db)).filter((r) => r.migration !== 'all');
assert.deepEqual(open, [{ migration: 'rls', state: 'ROW LEVEL SECURITY OFF (run what is in the next column)', missing: 'alter table purchases enable row level security;' }]);
await db.exec('alter table purchases enable row level security;');
console.log('ok  a table without row level security is named, with the line that fixes it');

await db.exec('drop table ad_impression_days cascade;');
const dropped = (await answer(db)).filter((r) => r.migration !== 'all');
const r103 = dropped.find((r) => r.migration === '103');
assert.ok(r103 && r103.state === 'PARTLY RUN' && /^table ad_impression_days/.test(r103.missing), '103 PARTLY RUN, the table named');
// 117 changed a column of that table, so it is missing that much too.
assert.ok(dropped.every((r) => r.migration === '103' || /ad_impression_days/.test(r.missing)), 'nothing else reported');
console.log(`ok  the whole chain without ad_impression_days answers ${dropped.map((r) => `${r.migration} ${r.state}`).join(', ')}`);
